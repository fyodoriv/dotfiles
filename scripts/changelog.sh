#!/bin/bash
# Generate CHANGELOG.md from Conventional Commit subjects with git-cliff
# (rule 0: GET, then WRAP; config in cliff.toml). Never edit the changelog by
# hand; run `make changelog` (the monthly checkup does).
#
# Usage: scripts/changelog.sh [ref]   (default: origin/feat/chezmoi, else HEAD)
# dotfiles ships from its branch and has no release tags, so the changelog is
# one list of every listed commit up to <ref>. The header names that commit,
# so tests/changelog.bats can regenerate the file and prove nobody edited it.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
command -v git-cliff >/dev/null || { echo "changelog: git-cliff missing — fix: brew install git-cliff" >&2; exit 1; }
ref="${1:-}"
if [ -z "$ref" ]; then
  if git rev-parse -q --verify origin/feat/chezmoi >/dev/null; then ref=origin/feat/chezmoi; else ref=HEAD; fi
fi
full="$(git rev-parse "$ref^{commit}")"
root="$(git rev-list --max-parents=0 "$full" | tail -1)"

cat <<HEADER
# Changelog

Generated by \`scripts/changelog.sh\` (git-cliff) from Conventional Commit
subjects up to commit ${full:0:12}. Do not edit by hand: run \`make changelog\`.
dotfiles ships from its branch and has no release tags, so this is one list,
newest first. Only \`feat\`, \`fix\`, \`perf\`, and \`refactor\` commits are listed.
Older hand-written notes are in [docs/changelog-archive.md](docs/changelog-archive.md).
HEADER
if [ "$root" = "$full" ]; then exit 0; fi
git-cliff --config cliff.toml "$root..$full" 2>/dev/null
